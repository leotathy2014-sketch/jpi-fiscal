create table if not exists public.whatsapp_manual_senders (
  id bigint generated by default as identity primary key,
  nome text not null,
  numero text not null unique,
  ativo boolean not null default true,
  ordem smallint not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid,
  constraint whatsapp_manual_senders_nome_check check (length(trim(nome)) between 1 and 60),
  constraint whatsapp_manual_senders_numero_check check (numero ~ '^55[1-9][0-9]{9,10}$'),
  constraint whatsapp_manual_senders_ordem_check check (ordem between 1 and 4)
);

