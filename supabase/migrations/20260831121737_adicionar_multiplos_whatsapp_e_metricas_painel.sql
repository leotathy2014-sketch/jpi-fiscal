create or replace function private.get_delivery_dashboard_internal(
  p_start timestamptz default null,
  p_end timestamptz default null
)
returns table (
  canal text,
  enviados bigint,
  erros bigint,
  aguardando bigint,
  ultima_atividade timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null
     or private.current_jpi_role() not in ('admin','financeiro','secretaria','consulta') then
    raise exception 'Usuário sem permissão para visualizar o painel.' using errcode = '42501';
  end if;

  return query
  select
    case
      when e.canal in ('whatsapp','whatsapp_manual') then 'whatsapp'
      when e.canal = 'agenda_edu' then 'agenda_edu'
      else 'email'
    end as canal,
    count(*) filter (where e.status = 'enviado') as enviados,
    count(*) filter (where e.status = 'erro') as erros,
    count(*) filter (where e.status in ('enviando','aguardando_confirmacao')) as aguardando,
    max(coalesce(e.enviado_em,e.updated_at,e.created_at)) as ultima_atividade
  from public.nfse_entregas e
  where (p_start is null or e.created_at >= p_start)
    and (p_end is null or e.created_at < p_end)
  group by 1
  order by 1;
end;
$$;

revoke all on function private.get_delivery_dashboard_internal(timestamptz,timestamptz) from public, anon;
grant execute on function private.get_delivery_dashboard_internal(timestamptz,timestamptz) to authenticated;

create or replace function public.get_delivery_dashboard(
  p_start timestamptz default null,
  p_end timestamptz default null
)
returns table (
  canal text,
  enviados bigint,
  erros bigint,
  aguardando bigint,
  ultima_atividade timestamptz
)
language sql
security invoker
set search_path = ''
as $$
  select * from private.get_delivery_dashboard_internal(p_start,p_end);
$$;

