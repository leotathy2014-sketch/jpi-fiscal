create or replace function private.inspect_nfse_delivery_access_internal(p_token_hash text,p_backend_secret text)
returns table(valid boolean,competencia text,expires_at timestamptz,visualizado_em timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.valid_jpi_backend_secret(p_backend_secret) then
    raise exception 'Credencial interna do servidor inválida.' using errcode = '42501';
  end if;
  return query
  select l.expires_at > now(), m.competencia, l.expires_at, l.visualizado_em
  from private.nfse_entrega_links l
  join public.nfse_entregas e on e.id=l.entrega_id
  join public.mensalidades m on m.id=e.mensalidade_id
  where l.token_hash=p_token_hash;
end;
$$;

