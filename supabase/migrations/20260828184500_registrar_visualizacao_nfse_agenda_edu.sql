create or replace function private.open_nfse_delivery_access_internal(p_token_hash text,p_backend_secret text)
returns table(chave_acesso text,xml_base64 text,expires_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
  selected private.nfse_entrega_links%rowtype;
  opened_at timestamptz := now();
begin
  if not private.valid_jpi_backend_secret(p_backend_secret) then
    raise exception 'Credencial interna do servidor inválida.' using errcode = '42501';
  end if;
  select * into selected from private.nfse_entrega_links
  where token_hash=p_token_hash and expires_at > opened_at for update;
  if not found then return; end if;
  update private.nfse_entrega_links set
    visualizado_em=coalesce(visualizado_em,opened_at), ultimo_acesso_em=opened_at,
    visualizacoes=visualizacoes+1 where id=selected.id;
  update public.nfse_entregas set
    visualizado_em=coalesce(visualizado_em,opened_at), visualizacoes=visualizacoes+1,
    updated_at=opened_at where id=selected.entrega_id;
  return query select selected.chave_acesso,encode(selected.xml_content,'base64'),selected.expires_at;
end;
$$;

